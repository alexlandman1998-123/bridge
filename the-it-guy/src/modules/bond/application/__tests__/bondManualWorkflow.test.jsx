// @vitest-environment jsdom
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, expect, it, vi } from 'vitest'
import BondManualWorkflow from '../../../../components/bond/BondManualWorkflow.jsx'
const mocks = vi.hoisted(() => ({ context: vi.fn(), record: vi.fn(), request: vi.fn(), review: vi.fn(), url: vi.fn() }))
vi.mock('../../../../lib/api.js', () => ({ fetchBondTrackerContext: mocks.context, recordBondTrackerSubmission: mocks.record, requestManualBondDocument: mocks.request, reviewManualBondDocument: mocks.review, fetchBondApplicationPackDocumentUrl: mocks.url }))
afterEach(() => { cleanup(); vi.resetAllMocks() })
const context = {mode:'originator_tracker',canEdit:true,applicationId:null,requirements:[],submissions:[]}
it('records progress without any application, signing, document or statement-provider setup', async () => {
 mocks.context.mockResolvedValue(context); mocks.record.mockResolvedValue({id:'tracked'})
 const changed=vi.fn()
 render(<BondManualWorkflow transactionId="tx" onChanged={changed} />)
 const save=await screen.findByText('Save bank submission')
 expect(save.disabled).toBe(true)
 fireEvent.change(screen.getByLabelText('Bank'),{target:{value:'Any lender'}})
 fireEvent.change(screen.getByLabelText('Submission date'),{target:{value:'2026-11-01'}})
 fireEvent.click(save)
 await screen.findByText('Bank submission recorded in the tracker.')
 expect(changed).toHaveBeenCalledOnce()
 expect(mocks.record).toHaveBeenCalledWith(expect.objectContaining({transactionId:'tx',bankName:'Any lender',reference:'',notes:''}))
 expect(screen.queryByText('Prepare buyer application')).toBeNull()
 expect(screen.queryByText('Record consultant review')).toBeNull()
 expect(screen.queryByText('Accept signed original')).toBeNull()
})
it('keeps requested or rejected documents optional when recording a submission', async () => {
 mocks.context.mockResolvedValue({...context,requirements:[{id:'req',key:'income',title:'Income',canonicalId:'canonical',document:{id:'doc',status:'rejected'}}]})
 render(<BondManualWorkflow transactionId="tx" />)
 await screen.findByText('Save bank submission')
 fireEvent.change(screen.getByLabelText('Bank'),{target:{value:'FNB'}})
 fireEvent.change(screen.getByLabelText('Submission date'),{target:{value:'2026-11-01'}})
 expect(screen.getByText('Save bank submission').disabled).toBe(false)
})
it('saves an optional buyer document request with clear instructions and a retry key', async () => {
 mocks.context.mockResolvedValue(context); mocks.request.mockResolvedValue({requirementId:'req'})
 render(<BondManualWorkflow transactionId="tx" />)
 fireEvent.click(await screen.findByText('Documents and requests (optional)'))
 fireEvent.change(screen.getByLabelText('Instructions'),{target:{value:'Please supply all pages of your identity document.'}})
 fireEvent.click(screen.getByText('Save document request'))
 await screen.findByText(/Document request saved/)
 expect(mocks.request.mock.calls[0][0]).toMatchObject({transactionId:'tx',requestId:expect.any(String),type:'buyer_id_document',instruction:'Please supply all pages of your identity document.'})
})
it('reviews the exact current upload and requires replacement feedback', async () => {
 mocks.context.mockResolvedValue({...context,requirements:[{id:'req',title:'Payslips',canonicalId:'canonical',document:{id:'doc',name:'Payslips.pdf',file_path:'buyer/v2.pdf',status:'uploaded'}}]})
 mocks.review.mockResolvedValue({status:'rejected'})
 render(<BondManualWorkflow transactionId="tx" />)
 fireEvent.click(await screen.findByText('Documents and requests (optional)'))
 const replace=screen.getByText('Request replacement')
 expect(replace.disabled).toBe(true)
 fireEvent.change(screen.getByLabelText('Feedback for buyer'),{target:{value:'The last page is missing.'}})
 fireEvent.click(replace)
 await waitFor(()=>expect(mocks.review).toHaveBeenCalledOnce())
 expect(mocks.review.mock.calls[0][0]).toMatchObject({transactionId:'tx',requirementId:'req',documentId:'doc',expectedPath:'buyer/v2.pdf',action:'reject',feedback:'The last page is missing.'})
})
it('shows closed history without editable tracking controls', async () => {
 mocks.context.mockResolvedValue({...context,canEdit:false,submissions:[{id:'bank',bank_name:'FNB',status:'approved',reference:'TRACK-001'}]})
 render(<BondManualWorkflow transactionId="tx" />)
 await screen.findByText('FNB')
 expect(screen.queryByText('Save bank submission')).toBeNull()
 expect(screen.getByText(/Reference: TRACK-001/)).toBeTruthy()
})
it('ignores a late response from the previous deal', async () => {
 let resolveOld
 mocks.context.mockImplementation(({transactionId})=>transactionId==='old'?new Promise(resolve=>{resolveOld=resolve}):Promise.resolve(context))
 const {rerender}=render(<BondManualWorkflow transactionId="old" />)
 rerender(<BondManualWorkflow transactionId="new" />)
 await screen.findByText('Save bank submission')
 resolveOld({...context,canEdit:false})
 await waitFor(()=>expect(screen.queryByText(/This deal is closed/)).toBeNull())
})
