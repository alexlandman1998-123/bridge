it('queues an IMAP connection and clears the password as soon as it is submitted', async () => {
  mocks.imap.mockResolvedValue({status:'authorizing'})
  render(<EmailMailboxSettings {...props} />)
  fireEvent.click(await screen.findByRole('button',{name:/Jane jane@example.test/}))
  fireEvent.change(screen.getByLabelText('IMAP server'),{target:{value:'imap.example.test'}})
  fireEvent.change(screen.getByLabelText('IMAP password'),{target:{value:'app-password'}})
  fireEvent.click(screen.getByRole('button',{name:'Connect IMAP mailbox'}))
  expect(screen.getByLabelText('IMAP password').value).toBe('')
  await screen.findByText(/IMAP connection test queued/)
  expect(mocks.imap).toHaveBeenCalledWith({organisationId:org,channelId:personal.id,host:'imap.example.test',username:personal.address,password:'app-password'})
  expect(document.body.textContent).not.toContain('app-password')
})
