// @vitest-environment jsdom
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
const runtime = vi.hoisted(() => ({ load: vi.fn(), generate: vi.fn(), handoff: vi.fn(), download: vi.fn(), zip: vi.fn() }))
vi.mock('../../../services/campaignPackService', () => ({ loadCampaignPack: runtime.load, handoffCampaignDraft: runtime.handoff }))
vi.mock('../../../services/campaignPackRenderer', () => ({ generateCampaignPack: runtime.generate, campaignPackZip: runtime.zip, downloadCampaignAsset: runtime.download }))
import CampaignAssets from '../CampaignAssets'
const props = () => ({ organisationId: 'agency', userId: 'owner', campaign: { id: 'plan', revision: 1 }, canEdit: true, onEdit: vi.fn() })
const mount = (input = props()) => render(<MemoryRouter><CampaignAssets {...input} /></MemoryRouter>)
beforeEach(() => {
  vi.clearAllMocks()
  URL.createObjectURL = vi.fn(() => 'blob:preview')
  URL.revokeObjectURL = vi.fn()
  runtime.load.mockResolvedValue({ images: [{ id: 'cover' }] })
  runtime.generate.mockResolvedValue([{ id: 'photo-post', label: 'Photo post', width: 1080, height: 1080, filename: 'photo-post.png', blob: new Blob(['png']) }])
  runtime.zip.mockResolvedValue(new Blob(['zip']))
  runtime.handoff.mockResolvedValue({ id: 'email-draft', status: 'draft' })
})
afterEach(cleanup)
it('generates reviewable artwork, rechecks current facts for a download and releases preview URLs', async () => {
  const view = mount()
  fireEvent.click(screen.getByRole('button', { name: 'Prepare artwork' }))
  await screen.findByRole('img', { name: 'Photo post' })
  expect(runtime.load).toHaveBeenCalledTimes(2)
  fireEvent.click(screen.getByRole('button', { name: 'Download full pack (.zip)' }))
  await waitFor(() => expect(runtime.download).toHaveBeenCalled())
  expect(runtime.load).toHaveBeenCalledTimes(3)
  expect(runtime.zip).toHaveBeenCalled()
  view.unmount()
  expect(URL.revokeObjectURL).toHaveBeenCalledWith('blob:preview')
})
it('blocks a stale download without discarding a previously rendered preview', async () => {
  mount(); fireEvent.click(screen.getByRole('button', { name: 'Prepare artwork' }))
  await screen.findByRole('img', { name: 'Photo post' })
  runtime.load.mockRejectedValue(new Error('The listing changed.'))
  fireEvent.click(screen.getByRole('button', { name: 'Download', exact: true }))
  await screen.findByRole('alert')
  expect(runtime.download).not.toHaveBeenCalled()
  expect(screen.getByRole('img', { name: 'Photo post' })).toBeTruthy()
})
it('opens a saved and linked channel draft without sending or navigating automatically', async () => {
  mount(); fireEvent.click(screen.getByRole('button', { name: 'Create email draft' }))
  const link = await screen.findByRole('link', { name: 'Open email draft' })
  expect(link.getAttribute('href')).toBe('/marketing?section=email&view=create&id=email-draft')
  expect(runtime.handoff).toHaveBeenCalledWith('agency', 'owner', expect.objectContaining({ id: 'plan' }), 'email')
})
it('provides a name-only logo fallback and an actionable media failure', async () => {
  runtime.generate.mockRejectedValue(new Error('A listing photo or logo could not be loaded.'))
  mount(); fireEvent.click(screen.getByRole('checkbox', { name: 'Use agency-name branding instead of a logo' }))
  fireEvent.click(screen.getByRole('button', { name: 'Prepare artwork' }))
  await screen.findByRole('alert')
  expect(runtime.generate).toHaveBeenCalledWith(expect.anything(), { nameOnly: true })
})
it('does not generate or hand off for a view-only colleague', () => {
  mount({ ...props(), canEdit: false })
  expect(screen.queryByRole('button', { name: 'Prepare artwork' })).toBeNull()
  expect(runtime.load).not.toHaveBeenCalled()
})
it('blocks already-rendered image downloads if the saved cover is removed', async () => {
  mount(); fireEvent.click(screen.getByRole('button', { name: 'Prepare artwork' }))
  await screen.findByRole('img', { name: 'Photo post' })
  runtime.load.mockResolvedValue({ images: [] })
  fireEvent.click(screen.getByRole('button', { name: 'Download', exact: true }))
  expect((await screen.findByRole('alert')).textContent).toContain('cover photo is no longer available')
  expect(runtime.download).not.toHaveBeenCalled()
})
it('prepares a branded checklist pack without a listing photo and names the general campaign download correctly',async()=>{
 runtime.load.mockResolvedValue({general:true,images:[],allowNoPhoto:true})
 mount({...props(),campaign:{id:'plan',revision:1,campaign_builder:{template:'first-time-buyer'}}})
 expect(screen.getByRole('heading',{name:'Your First-Time Buyer Starter pack'})).toBeTruthy()
 expect(screen.getByText(/Downloadable checklist \(.txt\)/)).toBeTruthy()
 fireEvent.click(screen.getByRole('button',{name:'Prepare artwork'}))
 fireEvent.click(await screen.findByRole('button',{name:'Download full pack (.zip)'}))
 await waitFor(()=>expect(runtime.download).toHaveBeenCalledWith(expect.anything(),'campaign-plan-r1.zip'))
})
