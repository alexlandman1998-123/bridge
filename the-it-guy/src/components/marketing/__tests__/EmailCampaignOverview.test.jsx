// @vitest-environment jsdom
import React from 'react'
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { EmailCampaignOverview } from '../EmailCampaigns'
const mocks = vi.hoisted(() => ({ workspace: vi.fn(), audiences: vi.fn(), preview: vi.fn(), saveAudience: vi.fn(), archiveAudience: vi.fn() }))
vi.mock('../EmailCampaignBuilder', () => ({ default: () => null }))
vi.mock('../../../context/AuthSessionContext', () => ({ useAuthSession: () => ({ authState: { currentWorkspace: { id: 'org' } } }) }))
vi.mock('../../../services/emailCampaignService', () => ({ getEmailCampaignWorkspace: mocks.workspace, getSavedAudiences: async (...args) => (await mocks.audiences(...args)) || [], previewSavedAudience: async (...args) => (await mocks.preview(...args)) || { count: 0, contacts: [] }, saveEmailAudience: mocks.saveAudience, archiveEmailAudience: mocks.archiveAudience }))
const draft = { id: 'draft', name: 'Spring listings', status: 'draft', updated_at: '2026-10-01T12:00:00Z' }
const sent = { id: 'sent', name: 'Buyer update', status: 'sent', sent_at: '2026-09-29T12:00:00Z' }
const workspace = (overrides = {}) => ({ campaigns: [draft, sent], performance: [], identities: [], usage: [], billingProfile: null, dailyPerformance: [], ...overrides })
afterEach(() => { cleanup(); vi.clearAllMocks() })
describe('Email campaign homepage', () => {
  it('combines search and status filters, then clears them', async () => {
    mocks.workspace.mockResolvedValue(workspace())
    render(<EmailCampaignOverview />)
    await screen.findByText('Spring listings')
    fireEvent.change(screen.getByLabelText('Search campaigns'), { target: { value: 'buyer' } })
    expect(screen.queryByText('Spring listings')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: /^draft/i }))
    expect(screen.getByText('No matching campaigns')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Clear filters' }))
    expect(screen.getByText('Spring listings')).toBeTruthy()
    expect(screen.getByText('Buyer update')).toBeTruthy()
  })
  it('opens drafts for editing and sent campaigns for reporting', async () => {
    mocks.workspace.mockResolvedValue(workspace())
    const create = vi.fn(), open = vi.fn()
    render(<EmailCampaignOverview onCreateCampaign={create} onOpenCampaign={open} />)
    fireEvent.click(await screen.findByRole('button', { name: /Spring listings/ }))
    expect(create).toHaveBeenCalledWith('draft')
    fireEvent.click(screen.getByRole('button', { name: /Buyer update/ }))
    expect(open).toHaveBeenCalledWith('sent')
    fireEvent.click(screen.getByRole('button', { name: 'Create campaign' }))
    expect(create).toHaveBeenLastCalledWith()
    expect(screen.getByText('Updated')).toBeTruthy()
    expect(screen.getByText('Not sent yet')).toBeTruthy()
  })
  it('shows one compact pre-send state and unavailable balance honestly', async () => {
    mocks.workspace.mockResolvedValue(workspace({ campaigns: [draft] }))
    render(<EmailCampaignOverview />)
    expect(await screen.findByText('Your first send starts the story')).toBeTruthy()
    expect(screen.queryByText('Campaigns by click rate')).toBeNull()
    expect(screen.getByText('Balance unavailable')).toBeTruthy()
    expect(screen.getByRole('button', { name: 'Check verification' }).disabled).toBe(true)
    expect(screen.queryByRole('button', { name: 'Top up wallet' })).toBeNull()
  })
  it('shows analytics with results and includes partial failures in Failed', async () => {
    mocks.workspace.mockResolvedValue(workspace({ campaigns: [sent, { id: 'failed', name: 'Interrupted send', status: 'partially_failed' }], performance: [{ campaign_id: 'sent', recipients: 50, delivered: 40, opened: 20, clicked: 4 }], dailyPerformance: [{ recipients: 50 }] }))
    render(<EmailCampaignOverview />)
    await screen.findByText('Campaigns by click rate')
    expect(screen.queryByText('Your first send starts the story')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: /^failed/i }))
    expect(screen.getByText('Interrupted send')).toBeTruthy()
    expect(screen.queryByRole('button', { name: /Buyer update.*recipients/ })).toBeNull()
  })
  it('shows five all-time cards with weighted rates that remain independent of list filters', async () => {
    mocks.workspace.mockResolvedValue(workspace({ performance: [
      { campaign_id: 'sent', recipients: 100, delivered: 80, opened: 40, clicked: 8 },
      { campaign_id: 'other', recipients: 20, delivered: 20, opened: 20, clicked: 2 },
    ] }))
    render(<EmailCampaignOverview />)
    await screen.findByText('Spring listings')
    const stats = screen.getByRole('region', { name: 'All-time campaign statistics' })
    const cards = within(stats).getAllByRole('article')
    expect(cards).toHaveLength(5)
    expect(cards.map((card) => card.querySelector('strong').textContent)).toEqual(['1', '60%', '120', '83%', '10%'])
    fireEvent.click(screen.getByRole('button', { name: /^draft/i }))
    expect(cards[0].querySelector('strong').textContent).toBe('1')
  })
  it('charts only the last 30 calendar days, switches metrics and opens ranked campaigns', async () => {
    const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Africa/Johannesburg', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date())
    mocks.workspace.mockResolvedValue(workspace({ campaigns: [sent], performance: [{ campaign_id: 'sent', recipients: 100, delivered: 90, opened: 50, clicked: 10, bounced: 5, unsubscribed: 2 }], dailyPerformance: [
      { metric_date: today, recipients: 100, delivered: 90, opened: 50, clicked: 10 },
      { metric_date: '2000-01-01', recipients: 9999, delivered: 9999, opened: 9999, clicked: 9999 },
    ] }))
    const open = vi.fn()
    render(<EmailCampaignOverview onOpenCampaign={open} />)
    const chart = await screen.findByRole('region', { name: 'Campaign trend' })
    expect(chart.querySelector('.email-trend-toolbar strong').textContent).toBe('90')
    expect(within(chart).getByRole('img', { name: 'Delivered by send date over the last 30 days' }).querySelectorAll('rect')).toHaveLength(30)
    fireEvent.click(within(chart).getByRole('button', { name: 'Opens' }))
    expect(chart.querySelector('.email-trend-toolbar strong').textContent).toBe('50')
    expect(within(chart).getByRole('img', { name: 'Opens by send date over the last 30 days' })).toBeTruthy()
    fireEvent.click(within(chart).getByRole('button', { name: 'Clicks' }))
    expect(chart.querySelector('.email-trend-toolbar strong').textContent).toBe('10')
    fireEvent.change(within(chart).getByLabelText('Inspect send date'), { target: { value: today } })
    expect(within(chart).getByLabelText('Inspect send date').options).toHaveLength(30)
    fireEvent.click(screen.getByRole('button', { name: /#1 campaign Buyer update/ }))
    expect(open).toHaveBeenCalledWith('sent')
    const health = screen.getByRole('region', { name: 'All-time audience health' })
    expect(within(health).getByText('5%')).toBeTruthy()
    expect(within(health).getByText('2')).toBeTruthy()
  })
  it('shows a truthful empty chart when sends fall outside the date range', async () => {
    mocks.workspace.mockResolvedValue(workspace({ performance: [{ campaign_id: 'sent', recipients: 100, delivered: 90 }], dailyPerformance: [{ metric_date: '2000-01-01', recipients: 100, delivered: 90 }] }))
    render(<EmailCampaignOverview />)
    expect(await screen.findByText('No delivered in this period')).toBeTruthy()
    expect(screen.queryByRole('img', { name: /by send date/ })).toBeNull()
  })
  it('switches to past campaigns without drafts or scheduled sends and keeps shared stats', async () => {
    mocks.workspace.mockResolvedValue(workspace({ campaigns: [draft, sent, { id: 'scheduled', name: 'Future send', status: 'scheduled' }, { id: 'cancelled', name: 'Cancelled send', status: 'cancelled' }] }))
    const change = vi.fn()
    render(<EmailCampaignOverview onViewChange={change} />)
    await screen.findByText('Spring listings')
    fireEvent.click(screen.getByRole('button', { name: 'Past campaigns' }))
    expect(change).toHaveBeenCalledWith('past')
    expect(screen.queryByText('Spring listings')).toBeNull()
    expect(screen.queryByText('Future send')).toBeNull()
    expect(screen.getByText('Buyer update')).toBeTruthy()
    expect(screen.getByText('Cancelled send')).toBeTruthy()
    expect(screen.getByRole('region', { name: 'All-time campaign statistics' })).toBeTruthy()
    expect(screen.queryByRole('region', { name: 'Performance intelligence' })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Overview' }))
    expect(screen.getByText('Spring listings')).toBeTruthy()
  })
  it('opens audience management, saves a segment and archives it only after confirmation', async () => {
    mocks.workspace.mockResolvedValue(workspace())
    mocks.audiences.mockResolvedValue([{ id: 'aud', name: 'Local buyers', filter_json: { operator: 'AND', rules: [{ field: 'contact_type', operator: 'in', value: ['buyer'] }] } }])
    mocks.preview.mockResolvedValue({ count: 12, contacts: [{ id: 'contact', name: 'Buyer Example', contactType: 'buyer' }] })
    render(<EmailCampaignOverview selectedView="audiences" />)
    await screen.findByText('Local buyers')
    fireEvent.click(screen.getByRole('button', { name: 'Edit Local buyers' }))
    fireEvent.change(screen.getByPlaceholderText('Name this audience'), { target: { value: 'Active buyers' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save audience' }))
    await waitFor(() => expect(mocks.saveAudience).toHaveBeenCalledWith(expect.objectContaining({ organisationId: 'org', audience: expect.objectContaining({ id: 'aud', name: 'Active buyers', filterJson: expect.objectContaining({ rules: [expect.objectContaining({ field: 'contact_type' })] }) }) })))
    await screen.findByText('Local buyers')
    fireEvent.click(screen.getByRole('button', { name: 'Delete Local buyers' }))
    expect(mocks.archiveAudience).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Delete audience' }))
    await waitFor(() => expect(mocks.archiveAudience).toHaveBeenCalledWith({ organisationId: 'org', audienceId: 'aud' }))
  })
  it('does not show setup or performance claims after a failed load', async () => {
    mocks.workspace.mockRejectedValue(new Error('Unable to load'))
    render(<EmailCampaignOverview />)
    await waitFor(() => expect(screen.getByRole('alert').textContent).toBe('Unable to load'))
    const stats = screen.getByRole('region', { name: 'All-time campaign statistics' })
    expect(within(stats).getAllByText('Data unavailable')).toHaveLength(5)
    expect(screen.queryByText('No campaigns yet')).toBeNull()
    expect(screen.queryByText('No verified sender')).toBeNull()
    expect(screen.queryByText('Your first send starts the story')).toBeNull()
  })
})
