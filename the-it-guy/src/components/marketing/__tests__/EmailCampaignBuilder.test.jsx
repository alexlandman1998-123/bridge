describe('Persisted draft identity and revision', () => {
  it('passes the loaded revision into save and uses each returned revision for later edits', async () => {
    const firstTime = '2026-10-25T10:00:00.000Z'
    const secondTime = '2026-10-25T10:01:00.000Z'
    const thirdTime = '2026-10-25T10:02:00.000Z'
    mocks.get.mockResolvedValue({ id: 'revision-draft', updated_at: firstTime, name: 'Saved campaign', subject: 'Property update', content_json: createEmailDocument() })
    mocks.save.mockReset().mockResolvedValueOnce({ id: 'revision-draft', updated_at: secondTime }).mockResolvedValueOnce({ id: 'revision-draft', updated_at: thirdTime })
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} campaignId="revision-draft" onBack={() => {}} />)
    await waitFor(() => expect(screen.getByLabelText('Campaign title').value).toBe('Saved campaign'))
    fireEvent.change(screen.getByLabelText('Campaign title'), { target: { value: 'First edit' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save as draft' }))
    await screen.findByText('Draft saved.')
    expect(mocks.save.mock.calls[0][0].campaign).toMatchObject({ id: 'revision-draft', clientId: 'revision-draft', updatedAt: firstTime, name: 'First edit' })
    fireEvent.change(screen.getByLabelText('Campaign title'), { target: { value: 'Second edit' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save as draft' }))
    await waitFor(() => expect(mocks.save).toHaveBeenCalledTimes(2))
    expect(mocks.save.mock.calls[1][0].campaign).toMatchObject({ id: 'revision-draft', updatedAt: secondTime, name: 'Second edit' })
    await waitFor(() => expect(screen.getByText('Saved just now')).toBeTruthy())
  })

  it('keeps the first-create retry identity and current edits after an interrupted response', async () => {
    const savedAt = '2026-10-25T10:01:00.000Z'
    let rejectFirst
    mocks.save.mockReset().mockImplementationOnce(() => new Promise((_resolve, reject) => { rejectFirst = reject })).mockImplementationOnce(async ({ campaign }) => ({ id: campaign.clientId, updated_at: savedAt })).mockImplementation(async ({ campaign }) => ({ id: campaign.id || campaign.clientId, updated_at: '2026-10-25T10:02:00.000Z' }))
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} onBack={() => {}} />)
    fireEvent.change(screen.getByLabelText('Campaign title'), { target: { value: 'Original create intent' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save as draft' }))
    await waitFor(() => expect(mocks.save).toHaveBeenCalledTimes(1))
    const originalId = mocks.save.mock.calls[0][0].campaign.clientId
    expect(originalId).toMatch(/^[a-f0-9-]{36}$/)
    expect(mocks.save.mock.calls[0][0].campaign.id).toBeUndefined()
    fireEvent.change(screen.getByLabelText('Campaign title'), { target: { value: 'Newest work stays visible' } })
    await act(async () => rejectFirst(new Error('Create response interrupted')))
    expect(await screen.findByText('Create response interrupted')).toBeTruthy()
    expect(screen.getByLabelText('Campaign title').value).toBe('Newest work stays visible')
    fireEvent.click(screen.getByRole('button', { name: 'Save as draft' }))
    await screen.findByText('Draft saved.')
    expect(mocks.save.mock.calls[1][0].campaign).toMatchObject({ clientId: originalId, name: 'Newest work stays visible' })
    expect(mocks.save.mock.calls[1][0].campaign.id).toBeUndefined()
    fireEvent.change(screen.getByLabelText('Campaign title'), { target: { value: 'Edit recovered draft' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save as draft' }))
    await waitFor(() => expect(mocks.save).toHaveBeenCalledTimes(3))
    expect(mocks.save.mock.calls[2][0].campaign).toMatchObject({ id: originalId, clientId: originalId, updatedAt: savedAt, name: 'Edit recovered draft' })
  })

  it('uses the returned revision while retaining edits made during an in-flight save', async () => {
    const originalTime = '2026-10-25T10:00:00.000Z'
    const savedTime = '2026-10-25T10:01:00.000Z'
    let resolveFirst
    mocks.get.mockResolvedValue({ id: 'parallel-edit', updated_at: originalTime, name: 'Saved original', subject: 'A property update', content_json: createEmailDocument() })
    mocks.save.mockReset().mockImplementationOnce(() => new Promise((resolve) => { resolveFirst = resolve })).mockResolvedValue({ id: 'parallel-edit', updated_at: '2026-10-25T10:02:00.000Z' })
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} campaignId="parallel-edit" onBack={() => {}} />)
    await waitFor(() => expect(screen.getByLabelText('Campaign title').value).toBe('Saved original'))
    fireEvent.change(screen.getByLabelText('Campaign title'), { target: { value: 'First saved change' } })
    fireEvent.click(screen.getByRole('button', { name: 'Save as draft' }))
    await waitFor(() => expect(mocks.save).toHaveBeenCalledTimes(1))
    fireEvent.change(screen.getByLabelText('Campaign title'), { target: { value: 'Latest change while saving' } })
    await act(async () => resolveFirst({ id: 'parallel-edit', updated_at: savedTime }))
    expect(screen.getByLabelText('Campaign title').value).toBe('Latest change while saving')
    fireEvent.click(screen.getByRole('button', { name: 'Save as draft' }))
    await waitFor(() => expect(mocks.save).toHaveBeenCalledTimes(2))
    expect(mocks.save.mock.calls[1][0].campaign).toMatchObject({ id: 'parallel-edit', updatedAt: savedTime, name: 'Latest change while saving' })
  })
})

