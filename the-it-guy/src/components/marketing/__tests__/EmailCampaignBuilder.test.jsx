// @vitest-environment jsdom
import React from 'react'
import { createEmailDocument } from '../../../../../supabase/functions/_shared/emailDocument.js'
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import EmailCampaignBuilder from '../EmailCampaignBuilder'
const mocks = vi.hoisted(() => ({ save: vi.fn(), get: vi.fn(), upload: vi.fn(), sendTest: vi.fn(), check: vi.fn(), preflight: vi.fn(), schedule: vi.fn() }))
vi.mock('../../../context/AuthSessionContext', () => ({ useAuthSession: () => ({ authState: { currentWorkspace: { name: 'Kingdom Real Estate' }, user: { email: 'agent@example.com' } } }) }))
vi.mock('../../../services/privateListingService', () => ({ getOrganisationPrivateListings: async () => [] }))
vi.mock('../../../services/emailCampaignAssetService', () => ({ getEmailCampaignAssets: async () => [], uploadEmailCampaignImage: mocks.upload, validateEmailCampaignImage: async () => {} }))
vi.mock('../../../services/emailCampaignService', () => ({ saveEmailCampaign: mocks.save, getEmailDraft: mocks.get, getEmailRevisions: async () => [], previewEmailAudience: async () => 12, createEmailSender: vi.fn(), createEmailSendingDomain: vi.fn(), checkEmailCampaignContent: mocks.check, preflightEmailCampaign: mocks.preflight, refreshEmailSenderVerification: vi.fn(), saveEmailTemplate: vi.fn(), scheduleEmailCampaign: mocks.schedule, sendEmailCampaignTest: mocks.sendTest, verifyEmailSendingDomain: vi.fn() }))
const workspace = { organisationId: 'org', userId: 'user', contacts: [], templates: [], savedAudiences: [], subscriptionTypes: [{ id: 'consent', name: 'Property updates' }], identities: [{ id: 'sender', display_name: 'Kingdom', from_email: 'hello@example.com', verification_status: 'verified' }], refresh: vi.fn() }
const Audience = () => <div>Audience controls</div>
beforeEach(() => {
  Object.defineProperty(URL, 'createObjectURL', { configurable: true, value: vi.fn(() => 'blob:preview') })
  Object.defineProperty(URL, 'revokeObjectURL', { configurable: true, value: vi.fn() })
})
afterEach(() => { cleanup(); vi.clearAllMocks(); vi.useRealTimers() })
it('keeps a development link when a saved email draft is reopened and edited', async () => {
  const context = { development_id: 'harbour', development_name: 'Harbour Heights' }
  mocks.get.mockResolvedValue({ id: 'linked-draft', name: 'Harbour launch', subject: 'Opening invitation', content_json: { ...createEmailDocument(), arch9_context: context } })
  mocks.save.mockResolvedValue({ id: 'linked-draft' })
  render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} campaignId="linked-draft" onBack={() => {}} />)
  await waitFor(() => expect(screen.getByLabelText('Internal campaign name').value).toBe('Harbour launch'))
  fireEvent.change(screen.getByRole('textbox', { name: 'Campaign title' }), { target: { value: 'Updated launch' } })
  fireEvent.click(screen.getByRole('button', { name: 'Save as draft' }))
  await waitFor(() => expect(mocks.save).toHaveBeenCalled())
  expect(mocks.save.mock.calls[0][0].campaign).toMatchObject({ id: 'linked-draft', developmentContext: context })
})
describe('Campaign setup', () => {
  it('shows server image errors on Review and discards the result when content changes', async () => {
    mocks.get.mockResolvedValue({ id: 'checked-draft', name: 'Designer campaign', subject: 'News', sender_identity_id: 'sender', subscription_type_id: 'consent', content_json: { ...createEmailDocument(), mode: 'advanced', advancedHtml: '<p>Ready HTML</p>' } })
    mocks.save.mockResolvedValue({ id: 'checked-draft' })
    mocks.check.mockResolvedValue({ ready: false, errors: ['A hosted image is missing.'], warnings: ['External image retention is not verified.'] })
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} campaignId="checked-draft" onBack={() => {}} />)
    await waitFor(() => expect(screen.getByLabelText('Internal campaign name').value).toBe('Designer campaign'))
    fireEvent.click(screen.getByRole('button', { name: /2 Audience/ }))
    await screen.findByText('12 eligible recipients')
    fireEvent.click(screen.getByRole('button', { name: /4 Review/ }))
    fireEvent.click(await screen.findByRole('button', { name: 'Check content and hosted images' }))
    expect((await screen.findByRole('alert')).textContent).toContain('A hosted image is missing.')
    expect(screen.getByRole('button', { name: 'Preflight & send' }).disabled).toBe(true)
    expect(screen.getByText('External image retention is not verified.')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: /Content Complete/ }))
    fireEvent.change(await screen.findByLabelText('Email HTML'), { target: { value: '<p>Updated HTML</p>' } })
    fireEvent.click(screen.getByRole('button', { name: /4 Review/ }))
    await screen.findByRole('button', { name: 'Check content and hosted images' })
    expect(screen.queryByText('A hosted image is missing.')).toBeNull()
    expect(screen.queryByText('External image retention is not verified.')).toBeNull()
    expect(screen.getByRole('button', { name: 'Preflight & send' }).disabled).toBe(false)
  })

  it('explains a content preflight failure without scheduling and allows compatibility warnings', async () => {
    mocks.get.mockResolvedValue({ id: 'checked-draft', name: 'Designer campaign', subject: 'News', sender_identity_id: 'sender', subscription_type_id: 'consent', content_json: { ...createEmailDocument(), mode: 'advanced', advancedHtml: '<div style="display:flex"><p>Ready HTML</p></div>' } })
    mocks.save.mockResolvedValue({ id: 'checked-draft' })
    mocks.preflight.mockResolvedValue({ ready: false, contentCheck: { ready: false, errors: ['A hosted image is incomplete.'], warnings: [] } })
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} campaignId="checked-draft" onBack={() => {}} />)
    await waitFor(() => expect(screen.getByLabelText('Internal campaign name').value).toBe('Designer campaign'))
    fireEvent.click(screen.getByRole('button', { name: /2 Audience/ }))
    await screen.findByText('12 eligible recipients')
    fireEvent.click(screen.getByRole('button', { name: /4 Review/ }))
    const send = await screen.findByRole('button', { name: 'Preflight & send' })
    expect(send.disabled).toBe(false)
    expect(screen.getByText(/Some email clients may change flex/)).toBeTruthy()
    fireEvent.click(send)
    await waitFor(() => expect(screen.getAllByRole('alert').some((element) => element.textContent.includes('A hosted image is incomplete.'))).toBe(true))
    expect(mocks.schedule).not.toHaveBeenCalled()
  })
  it('reviews an import before replacing the email, saves its asset references, and supports undo', async () => {
    const oldHtml = '<p>Original draft</p>'
    mocks.get.mockResolvedValue({ id: 'html-draft', name: 'Designer campaign', subject: 'Property news', sender_identity_id: 'sender', subscription_type_id: 'consent', content_json: { ...createEmailDocument(), mode: 'advanced', advancedHtml: oldHtml } })
    mocks.save.mockResolvedValue({ id: 'html-draft' })
    mocks.upload.mockResolvedValue({ id: 'hosted', organisation_id: 'org', public_url: 'https://images.example/hosted.png' })
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} campaignId="html-draft" onBack={() => {}} />)
    await waitFor(() => expect(screen.getByLabelText('Internal campaign name').value).toBe('Designer campaign'))
    fireEvent.click(screen.getByRole('button', { name: /3 Content/ }))
    fireEvent.click(await screen.findByRole('button', { name: 'Upload email' }))
    fireEvent.change(screen.getByLabelText('Email package or HTML and images'), { target: { files: [new File(['<img src="hero.png">'], 'email.html', { type: 'text/html' }), new File(['png'], 'hero.png', { type: 'image/png' })] } })
    await screen.findByTitle('Uploaded email preview')
    expect(screen.getByLabelText('Email HTML').value).toBe(oldHtml)
    expect(mocks.upload).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole('button', { name: 'Host images and replace email' }))
    await waitFor(() => expect(screen.getByLabelText('Email HTML').value).toContain('https://images.example/hosted.png'))
    expect(screen.queryByRole('dialog')).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: 'Save as draft' }))
    await waitFor(() => expect(mocks.save.mock.calls.some(([args]) => args.campaign.contentJson.importedEmail?.assets[0]?.id === 'hosted')).toBe(true))
    fireEvent.click(screen.getByRole('button', { name: 'Undo' }))
    expect(screen.getByLabelText('Email HTML').value).toBe(oldHtml)
  })

  it('blocks review and test sends when manually edited HTML still references local images', async () => {
    mocks.get.mockResolvedValue({ id: 'broken-draft', name: 'Designer campaign', subject: 'Property news', sender_identity_id: 'sender', subscription_type_id: 'consent', content_json: { ...createEmailDocument(), mode: 'advanced', advancedHtml: '<img src="images/missing.png">' } })
    mocks.save.mockResolvedValue({ id: 'broken-draft' })
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} campaignId="broken-draft" onBack={() => {}} />)
    await waitFor(() => expect(screen.getByLabelText('Internal campaign name').value).toBe('Designer campaign'))
    fireEvent.click(screen.getByRole('button', { name: /3 Content/ }))
    await screen.findByLabelText('Email HTML')
    fireEvent.click(screen.getAllByRole('button', { name: 'Continue' })[0])
    expect(await screen.findByLabelText('Email HTML')).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Send test' }))
    expect(screen.getAllByRole('button', { name: 'Send test' }).at(-1).disabled).toBe(true)
    expect(screen.getAllByText(/Upload or replace the local images/).length).toBeGreaterThan(0)
    expect(mocks.sendTest).not.toHaveBeenCalled()
  })
  it('provides the agency image library when editing an imported HTML draft', async () => {
    mocks.get.mockResolvedValue({ id: 'html-draft', name: 'Designer campaign', subject: 'Property news', sender_identity_id: 'sender', subscription_type_id: 'consent', content_json: { ...createEmailDocument(), mode: 'advanced', advancedHtml: '<p>Designer email</p>' } })
    mocks.save.mockResolvedValue({ id: 'html-draft' })
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} campaignId="html-draft" onBack={() => {}} />)
    await waitFor(() => expect(screen.getByLabelText('Internal campaign name').value).toBe('Designer campaign'))
    fireEvent.click(screen.getByRole('button', { name: /3 Content/ }))
    expect(await screen.findByRole('region', { name: 'Campaign image library' })).toBeTruthy()
    expect(screen.getByLabelText('Email HTML').value).toBe('<p>Designer email</p>')
    expect(screen.getByLabelText('Upload campaign image')).toBeTruthy()
  })
  it('blocks future steps with field-level guidance and synchronizes campaign title', async () => {
    mocks.save.mockResolvedValue({ id: 'draft-1' })
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} onBack={() => {}} />)
    expect(screen.getByRole('button', { name: /Continue to audience/ }).disabled).toBe(true)
    fireEvent.change(screen.getByRole('textbox', { name: 'Campaign title' }), { target: { value: 'September buyers' } })
    expect(screen.getByLabelText('Internal campaign name')).toHaveProperty('value', 'September buyers')
    fireEvent.click(screen.getByRole('button', { name: /4 Review/ }))
    expect(await screen.findByRole('alert')).toHaveProperty('textContent', 'Complete the required campaign details before continuing.')
    expect(screen.getByText('Add a subject line before continuing.')).toBeTruthy()
  })
  it('lets users return to completed steps to fix invalid edits', async () => {
    mocks.save.mockResolvedValue({ id: 'draft-1' })
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} onBack={() => {}} />)
    fireEvent.change(screen.getByLabelText('Subject line'), { target: { value: 'A property update' } })
    fireEvent.change(screen.getByLabelText(/Send permission/), { target: { value: 'consent' } })
    fireEvent.change(screen.getByLabelText(/^From/), { target: { value: 'sender' } })
    fireEvent.click(screen.getByRole('button', { name: /3 Content/ }))
    await screen.findByRole('heading', { name: 'Edit content' })
    fireEvent.change(screen.getByRole('textbox', { name: 'Campaign title' }), { target: { value: '' } })
    fireEvent.click(screen.getByRole('button', { name: /Details Complete/ }))
    expect(await screen.findByLabelText('Internal campaign name')).toHaveProperty('value', '')
    expect(screen.getByText('Give your campaign an internal name.')).toBeTruthy()
  })
  it('saves incomplete drafts once and retains edits made during an in-flight save', async () => {
    let resolveFirst
    mocks.save.mockImplementationOnce(() => new Promise((resolve) => { resolveFirst = resolve })).mockResolvedValue({ id: 'draft-1' })
    render(<EmailCampaignBuilder workspace={workspace} AudienceStudio={Audience} onBack={() => {}} />)
    fireEvent.click(screen.getByRole('button', { name: 'Save as draft' }))
    await waitFor(() => expect(mocks.save).toHaveBeenCalledTimes(1))
    fireEvent.change(screen.getByRole('textbox', { name: 'Campaign title' }), { target: { value: 'Latest edit' } })
    await act(async () => resolveFirst({ id: 'draft-1' }))
    await waitFor(() => expect(mocks.save).toHaveBeenCalledTimes(2), { timeout: 2200 })
    expect(mocks.save.mock.calls[1][0].campaign).toMatchObject({ id: 'draft-1', name: 'Latest edit' })
  })
})
