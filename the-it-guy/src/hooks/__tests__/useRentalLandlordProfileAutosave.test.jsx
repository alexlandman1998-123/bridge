it('retains a failed save, allows retry, and distinguishes a workspace refresh failure from save failure',async()=>{
  api.save.mockRejectedValueOnce(new Error('Connection failed'))
  const onReload=vi.fn().mockRejectedValue(new Error('Read failed')),hook=show({onReload})
  act(()=>hook.result.current.updateProfile('name','Retain this'))
  await act(()=>vi.advanceTimersByTimeAsync(801));expect(hook.result.current.status).toBe('error')
  expect(hook.result.current.profile.name).toBe('Retain this')
  await act(()=>hook.result.current.saveNow())
  expect(hook.result.current.status).toBe('saved');expect(hook.result.current.notice).toContain('workspace refresh')
})
