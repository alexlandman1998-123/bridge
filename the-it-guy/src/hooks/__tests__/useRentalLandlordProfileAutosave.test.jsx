it.each(landlordAcceptanceScenarios)('$label: recovers typing and explicit clears after a pending save fails, then verifies a retry', async scenario => {
 const initial=landlordAcceptanceProfile(scenario,'autosave')
 let rejectSave
 api.save.mockImplementationOnce(()=>new Promise((_resolve,reject)=>{rejectSave=reject}))
 api.read.mockResolvedValue(receipt(initial))
 const hook=show({lead:leadFor(initial)})
 act(()=>hook.result.current.updateProfile('taxNumber','First tax edit'))
 await act(()=>vi.advanceTimersByTimeAsync(801))
 act(()=>hook.result.current.updateProfile({taxNumber:'',name:'Latest owner typing'}))
 await act(async()=>{rejectSave(new Error('Connection failed during save'))})
 expect(hook.result.current.status).toBe('error')
 expect(api.save).toHaveBeenCalledTimes(1)
 hook.unmount()
 const reopened=show({lead:leadFor(initial)})
 expect(reopened.result.current.profile).toMatchObject({type:scenario.type,taxNumber:'',name:'Latest owner typing'})
 expect(reopened.result.current.profile.people).toEqual(initial.people)
 expect(reopened.result.current.notice).toContain('Recovered')
 await act(()=>reopened.result.current.saveNow())
 expect(api.save).toHaveBeenCalledTimes(2)
 expect(api.save.mock.calls[1][1]).toMatchObject({type:scenario.type,taxNumber:'',name:'Latest owner typing'})
 expect(reopened.result.current.status).toBe('saved')
 expect(readLandlordProfileDraft(landlordProfileDraftKey(context,'lead'))).toBeNull()
})
