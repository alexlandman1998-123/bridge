import assert from 'node:assert/strict'
import { createRentalCrmLeadMetadata, getRentalCrmLeadMetadata, isRentalCrmLead, patchRentalCrmLeadMetadata } from '../rentalCrmLeadModel.js'

const created = createRentalCrmLeadMetadata({ organisationId: 'org-1', role: 'landlord', stage: 'new', relationships: { propertyId: 'property-1' }, consents: { privacy: true }, qualification: { expectedMonthlyRent: 18000 } })
assert.equal(created.leadType, 'rental')
assert.equal(created.role, 'landlord')
assert.equal(created.relationships.propertyId, 'property-1')
assert.equal(created.consents.privacy, 'granted')
assert.equal(created.qualification.expectedMonthlyRent, 18000)
assert.equal(created.relationships.listingId, null)
const patched = patchRentalCrmLeadMetadata(created, { stage: 'mandate_signed', relationships: { mandateId: 'mandate-1', listingId: 'listing-1' }, consents: { screening: 'granted' } })
assert.equal(patched.stage, 'mandate_signed')
assert.equal(patched.relationships.mandateId, 'mandate-1')
assert.equal(patched.relationships.listingId, 'listing-1')
assert.equal(patched.consents.screening, 'granted')
const legacy = getRentalCrmLeadMetadata({ rawEnquiryPayload: { arch9RentalLead: true, classification: 'rental', role: 'tenant', stage: 'viewing', desiredArea: 'Sea Point' } })
assert.equal(legacy.stage, 'viewing')
assert.equal(isRentalCrmLead({ rawEnquiryPayload: legacy }), true)
const savedColumnLink = getRentalCrmLeadMetadata({ listing_id: 'saved-rental', rawEnquiryPayload: { arch9RentalLead: true, role: 'tenant', relationships: { vacancyId: 'vacancy-1' } } })
assert.equal(savedColumnLink.relationships.listingId, 'saved-rental')
assert.equal(savedColumnLink.relationships.vacancyId, 'vacancy-1')
assert.equal(getRentalCrmLeadMetadata({ enquired_listing_id: 'enquired-rental', rawEnquiryPayload: { classification: 'rental' } }).relationships.listingId, 'enquired-rental')
assert.equal(getRentalCrmLeadMetadata({ listing_id: 'older-column-link', rawEnquiryPayload: { rentalCrm: { classification: 'rental', relationships: { listing_id: 'explicit-rental' } } } }).relationships.listingId, 'explicit-rental')
const protectedMetadata = createRentalCrmLeadMetadata({ organisationId: 'org-1', role: 'landlord', legacy: { arch9RentalLead: false, classification: 'sale', leadType: 'buyer', role: 'tenant', organisationId: 'foreign', custom: 'kept' } })
assert.equal(protectedMetadata.arch9RentalLead, true)
assert.equal(protectedMetadata.classification, 'rental')
assert.equal(protectedMetadata.role, 'landlord')
assert.equal(protectedMetadata.organisationId, 'org-1')
assert.equal(protectedMetadata.custom, 'kept')
const nested = patchRentalCrmLeadMetadata({ raw_enquiry_payload: { providerReference: 'PP:123', rental_crm: { classification: 'rental', role: 'landlord', stage: 'new' } } }, { stage: 'contacted' })
assert.equal(getRentalCrmLeadMetadata(nested).stage, 'contacted')
assert.equal(nested.providerReference, 'PP:123')
assert.equal(nested.rental_crm, undefined)
assert.throws(() => patchRentalCrmLeadMetadata(created, { role: 'tenant' }), /cannot switch/)
assert.equal(isRentalCrmLead({ raw_enquiry_payload: { arch9RentalLead: 'true', rentalCrm: { classification: 'sale' } } }), true)
assert.equal(isRentalCrmLead({ rawEnquiryPayload: { classification: 'sale', rentalCrm: { classification: 'rental' } } }), true)
assert.equal(isRentalCrmLead({ rawEnquiryPayload: { role: 'owner', propertyDescription: 'Suitable as a rental investment' } }), false)
assert.equal(isRentalCrmLead({rawEnquiryPayload:{},raw_enquiry_payload:{rental_crm:{classification:'rental'}}}),true)
assert.equal(getRentalCrmLeadMetadata({rawEnquiryPayload:{},raw_enquiry_payload:{classification:'rental',role:'landlord'}}).role,'landlord')
assert.equal(getRentalCrmLeadMetadata({ organisation_id: 'saved-org', lead_id: 'saved-lead', raw_enquiry_payload: { classification: 'rental', organisationId: 'foreign', leadId: 'foreign' } }).organisationId, 'saved-org')
console.log('Rental CRM lead model tests passed.')
