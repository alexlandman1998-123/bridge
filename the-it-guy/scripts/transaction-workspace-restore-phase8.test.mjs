import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { getTransactionWorkspaceDatasetForTab } from '../src/pages/transaction-workspace/datasetRegistry.js'
const source = readFileSync('src/pages/AttorneyTransactionDetail.jsx', 'utf8')
const start = source.indexOf('const AGENT_WORKSPACE_TABS = [')
const end = source.indexOf('const BOND_ORIGINATOR_WORKSPACE_TABS = [', start)
const tabs = source.slice(start, end)
for (const label of ['Overview', 'Deal Setup', 'Documents', 'Finance', 'Conveyancing', 'Activity', 'Parties']) assert.ok(tabs.includes(`label: '${label}'`))
assert.doesNotMatch(tabs, /label: 'Roleplayers'|label: 'Tasks'/)
assert.match(source, /workspaceLabel=""/)
assert.match(source, /showWorkflowProgress=\{!isTransactionOperatorView\}/)
assert.match(source, /tabs=\{isTransactionOperatorView[\s\S]*workspaceMenuTabs.map/)
assert.match(source, /<TransactionDetailRouteShell/)
assert.match(source, /isTransactionOperatorView && activeWorkspaceMenu === 'transfer'/)
assert.match(source, /workspaceRole === 'attorney' && activeWorkspaceMenu === 'transfer'/)
assert.match(source, /<AgentConveyancingJourney/)
assert.match(source, /agentShouldUseOriginatorFinanceTracker/)
assert.match(source, /financeManagedByForTransaction === 'bond_originator'/)
assert.match(source, /function isAgentSafeWorkflowUpdate/)
assert.match(source, /function isInternalActivityEntry/)
for (const [tab, dataset] of [['documents', 'documents'], ['finance', 'finance'], ['activity', 'activity'], ['stakeholders', 'partners'], ['transfer', 'workflow']]) assert.equal(getTransactionWorkspaceDatasetForTab(tab), dataset)
console.log('Transaction workspace: current tabs, role boundaries, loading shell, finance ownership and scoped datasets passed')
