import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const source = readFileSync('src/pages/AttorneyTransactionDetail.jsx', 'utf8')
const activity = readFileSync('src/pages/transaction-workspace/tabs/ActivityWorkspaceTab.jsx', 'utf8')
const start = source.indexOf("(workspaceRole === 'attorney' || isTransactionOperatorView) && activeWorkspaceMenu === 'activity'")
const end = source.indexOf("activeWorkspaceMenu === 'stakeholders'", start)
assert.ok(start > 0 && end > start, 'agent and attorney activity must share the activity tab')
const block = source.slice(start, end)
assert.match(block, /<ArchlineActivityWorkspace/)
assert.match(block, /<form onSubmit=\{handleAddDiscussion\}/)
assert.match(block, /<DiscussionComposerControls/)
assert.match(block, /visibilityOptions=\{effectiveDiscussionVisibilityOptions\}/)
assert.match(block, /disabled=\{discussionSubmitDisabled\}/)
assert.match(source, /addAttorneyTransactionUpdate/)
assert.match(source, /useMatterConversation: true/)
assert.match(source, /messageCommandId: discussionMessageRequestRef.current.commandId/)
assert.match(source, /canUseSelectedDiscussionAudience/)
assert.match(source, /updateType: discussionType/)
assert.match(activity, /onFilterChange\?\.\(filter.key\)/)
assert.match(activity, /No activity matches this filter/)
assert.match(activity, /\['Conveyancing', Workflow, 'transfer'\]/)
assert.doesNotMatch(activity, /\['Tasks', ListChecks, 'tasks'\]/)
console.log('Transaction activity: filters, scoped composer, disabled empty submit and valid quick-action destinations passed')
