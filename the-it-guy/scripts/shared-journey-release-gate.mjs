export const ROLES = ['attorney', 'agent', 'developer', 'buyer', 'seller']
export const SCENARIOS = [
  'cash-individual-unmarried', 'cash-individual-married-cop',
  'bond-individual-married-anc', 'bond-company', 'hybrid-company',
  'transfer-with-cancellation',
]
export const OUTCOMES = ['in_progress', 'waiting', 'blocked', 'completed', 'completed_externally', 'not_applicable', 'reopened']
export const scenarioLanes = scenario => scenario === 'transfer-with-cancellation' ? ['transfer', 'cancellation']
  : scenario.startsWith('cash-') ? ['transfer'] : ['transfer', 'bond']
export const SAFETY_CHECKS = [
  'private-notes-not-exposed', 'audience-restrictions', 'revoked-access-denied',
  'other-matter-access-denied', 'retry-no-duplicate-events', 'stale-write-rejected',
  'offline-reconnect', 'background-tab-recovery', 'drafts-preserved',
  'header-work-dashboard-aligned', 'buyer-seller-browser-journey-aligned',
  'comments-cross-role', 'reconciliation-reviewed', 'migration-history-aligned',
  'rollback-rehearsed',
]
const hash = value => typeof value === 'string' && /^[a-f0-9]{64}$/.test(value)
// Evidence is an operator-attested staging record, not generated by unit tests.
// Never infer a live pass from absent, stale or partial evidence.
export function evaluateJourneyRelease({ local, staging, now = Date.now() }) {
  const blockers = []
  if (!local || local.status !== 'passed' || !hash(local.sourceDigest)) blockers.push('LOCAL_ACCEPTANCE_FAILED')
  if (!staging) return { decision: 'blocked', blockers: [...blockers, 'STAGING_EVIDENCE_MISSING'], productionChanged: false }
  if (staging.schemaVersion !== 1 || staging.environment !== 'staging' || !/^[a-z0-9]{20}$/.test(staging.projectRef || '') || !staging.deploymentId || !staging.reviewedBy) blockers.push('STAGING_IDENTITY_INCOMPLETE')
  if (!hash(staging.sourceDigest) || staging.sourceDigest !== local?.sourceDigest) blockers.push('CANDIDATE_MISMATCH')
  const age = now - Date.parse(staging.recordedAt)
  if (!Number.isFinite(age) || age < 0 || age > 86400000) blockers.push('STAGING_EVIDENCE_STALE')
  for (const scenario of SCENARIOS) for (const laneKey of scenarioLanes(scenario)) for (const outcome of OUTCOMES) {
    const matches = (staging.transitions || []).filter(t => t.scenario === scenario && t.laneKey === laneKey && t.outcome === outcome)
    if (matches.length !== 1) { blockers.push(`MISSING_OR_DUPLICATE_TRANSITION:${scenario}:${laneKey}:${outcome}`); continue }
    const t = matches[0], committed = Date.parse(t.committedAt)
    if (!t.matterId || !t.taskId || !Number.isSafeInteger(t.beforeRevision) || !Number.isSafeInteger(t.afterRevision) || t.afterRevision <= t.beforeRevision || !Number.isFinite(committed) || committed > Date.parse(staging.recordedAt) || now - committed > 86400000) blockers.push(`INVALID_TRANSITION:${scenario}:${outcome}`)
    const reads = t.reads || []
    for (const role of ROLES) {
      const observed = reads.filter(r => r.role === role)
      const read = observed[0], elapsed = Date.parse(read?.observedAt) - committed
      if (observed.length !== 1 || read.revision !== t.afterRevision || read.taskId !== t.taskId || read.taskStatus !== (outcome === 'reopened' ? 'not_started' : outcome) || !hash(read.snapshotDigest) || !Number.isFinite(elapsed) || elapsed < 0 || elapsed > 30000 || Date.parse(read.observedAt) > Date.parse(staging.recordedAt)) blockers.push(`ROLE_NOT_SYNCED:${scenario}:${laneKey}:${outcome}:${role}`)
    }
    if (new Set(reads.filter(r => ROLES.includes(r.role)).map(r => r.snapshotDigest)).size !== 1) blockers.push(`SNAPSHOT_MISMATCH:${scenario}:${outcome}`)
  }
  for (const check of SAFETY_CHECKS) {
    const result = staging.checks?.[check]
    if (result?.status !== 'passed' || typeof result.evidenceRef !== 'string' || !result.evidenceRef.trim()) blockers.push(`CHECK_NOT_VERIFIED:${check}`)
  }
  return { decision: blockers.length ? 'blocked' : 'ready_for_controlled_release', blockers, productionChanged: false }
}
