import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

export async function runHandoffQueueChecks({ db, owner, partner, user }) {
  const q = (sql, args = []) => db.query(sql, args)
  await db.exec(readFileSync(new URL('../../../supabase/migrations/20261004090057_transaction_handoff_organisation_queue.sql',import.meta.url),'utf8'))
  const read=async (org=owner,bucket='all',limit=100,offset=0)=>(await q('select bridge_read_organisation_handoff_queue($1,$2,$3,$4) result',[org,bucket,limit,offset])).rows[0].result
  await q("select set_config('test.uid',$1,false)",[user])
  assert.equal((await read(partner)).code,'organisation_authority_required')
  await q("update organisation_users set scope_level='branch' where organisation_id=$1 and user_id=$2",[owner,user])
  assert.equal((await read()).success,false)
  await q("update organisation_users set scope_level='workspace_hq' where organisation_id=$1 and user_id=$2",[owner,user])
  const create=async (org=owner)=>(await q(`insert into transactions(id,organisation_id,finance_type,finance_managed_by,onboarding_status,transaction_reference) values(gen_random_uuid(),$1,'bond','bond_originator','signed_otp_received','Queue matter') returning id`,[org])).rows[0].id
  const tx=await create()
  await q(`insert into transaction_role_players(id,transaction_id,role_type,assigned_organisation_id,status,assignment_status) values(gen_random_uuid(),$1,'bond_originator',$2,'active','active')`,[tx,partner])
  const h=(await q("select * from transaction_handoffs where transaction_id=$1 and role_type='bond_originator'",[tx])).rows[0]
  await q('delete from transaction_handoff_dispatch_jobs where handoff_id=$1 and generation=$2',[h.id,h.dispatch_generation])
  const orphan=await create()
  await q('delete from transaction_handoffs where transaction_id=$1',[orphan])
  const foreign=await create(partner)
  const before=(await q('select count(*)::int n from transaction_handoff_dispatch_jobs')).rows[0].n
  let queue=await read()
  assert.equal(queue.success,true)
  assert.equal(queue.items.find(item=>item.handoff_id===h.id).queue_reason,'dispatch_job_missing')
  assert.equal(queue.items.find(item=>item.transaction_id===orphan).queue_reason,'register_missing')
  assert.equal(queue.items.some(item=>item.transaction_id===foreign),false)
  assert.ok(queue.counts.data_gap>=2)
  assert.equal((await read(owner,'data_gap')).items.every(item=>item.bucket==='data_gap'),true)
  const first=await read(owner,'all',1,0),second=await read(owner,'all',1,1)
  assert.equal(first.items.length,1);assert.equal(first.hasMore,true)
  assert.notEqual(first.items[0].queue_id,second.items[0].queue_id)
  assert.equal(first.total,queue.total)
  assert.deepEqual(first.counts,queue.counts)
  assert.equal((await read(owner,'bad-filter')).code,'invalid_filter')
  assert.equal((await q('select count(*)::int n from transaction_handoff_dispatch_jobs')).rows[0].n,before,'queue read does not repair or requeue records')
  // Expiry is evaluated at read time even without another source update.
  const invited=await create()
  await q(`insert into transaction_partner_invitations(id,transaction_id,role_type,company_name,email,status,expires_at) values(gen_random_uuid(),$1,'bond_originator','External Partner','external@example.org','pending',now()+interval '1 day')`,[invited])
  assert.equal((await read()).items.find(item=>item.transaction_id===invited && item.role_type==='bond_originator').bucket,'invitation')
  await q('update transaction_partner_invitations set expires_at=now()-interval \'1 minute\' where transaction_id=$1',[invited])
  assert.equal((await read()).items.find(item=>item.transaction_id===invited && item.role_type==='bond_originator').queue_reason,'invitation_expired')
  // Persisted email evidence and native preparation are checked separately.
  await q(`insert into transaction_handoff_dispatch_jobs(handoff_id,generation,channel,destination_organisation_id,status) values($1,$2,'workspace',$3,'sent')`,[h.id,h.dispatch_generation,partner])
  assert.equal((await read()).items.find(item=>item.handoff_id===h.id).queue_reason,'native_matter_missing')
  await q(`insert into transaction_bond_applications(transaction_id,application_type,bank_name,status,assigned_organisation_id,assignment_status) values($1,'originator_intake','Intake','pending',$2,'organisation_queue')`,[tx,partner])
  await q('update transaction_handoffs set workspace_prepared_at=now() where id=$1',[h.id])
  assert.equal((await read()).items.find(item=>item.handoff_id===h.id).queue_reason,'delivery_intent_missing')
  await q('begin')
  await q("update transaction_partner_assignments set assignment_status='declined' where transaction_id=$1",[tx])
  assert.equal((await read()).items.find(item=>item.handoff_id===h.id).queue_reason,'partner_assignment_missing')
  await q('rollback')
  const email=(await q(`insert into transaction_handoff_dispatch_jobs(handoff_id,generation,channel,recipient_key,destination_organisation_id,status) values($1,$2,'email','test',$3,'sent') returning id`,[h.id,h.dispatch_generation,partner])).rows[0].id
  assert.equal((await read()).items.find(item=>item.handoff_id===h.id).queue_reason,'provider_receipt_missing')
  await q("update transaction_handoff_dispatch_jobs set provider_id='receipt',first_provider_attempt_at=now() where id=$1",[email])
  assert.equal((await read()).items.find(item=>item.handoff_id===h.id).queue_reason,'frozen_payload_missing')
  await q("insert into handoff_private.email_payloads values($1,'{\"secretToken\":\"must-not-leak\"}')",[email])
  await q('select handoff_private.refresh_dispatch($1)',[h.id])
  const since=(await read()).items.find(item=>item.handoff_id===h.id).pending_since
  await q('update transaction_handoffs set updated_at=now() where id=$1',[h.id])
  assert.equal((await read()).items.find(item=>item.handoff_id===h.id).pending_since,since)
  assert.equal((await read()).items.find(item=>item.handoff_id===h.id).bucket,'receipt')
  await q("update transaction_handoffs set acceptance_status='accepted' where id=$1",[h.id])
  assert.equal((await read()).items.some(item=>item.handoff_id===h.id),false,'successful delivery plus receipt leaves the queue')
  queue=await read()
  const encoded=JSON.stringify(queue)
  assert.equal(encoded.includes('external@example.org'),false)
  assert.equal(encoded.includes('must-not-leak'),false)
  await q("update transactions set status='cancelled' where id=$1",[orphan])
  assert.equal((await read()).items.some(item=>item.transaction_id===orphan),false)
  await q('update transaction_handoffs set owner_organisation_id=$1 where id=$2',[partner,h.id])
  assert.equal((await read()).items.find(item=>item.handoff_id===h.id).queue_reason,'handoff_owner_mismatch')
  const partnerManager='50000000-0000-0000-0000-000000000001'
  await q(`insert into auth.users values($1,'queue-manager@example.org',now())`,[partnerManager])
  await q(`insert into organisation_users(organisation_id,user_id,status,role,scope_level) values($1,$2,'active','owner','workspace_hq')`,[partner,partnerManager])
  await q("select set_config('test.uid',$1,false)",[partnerManager])
  assert.equal((await read()).code,'organisation_authority_required','a partner owner cannot enumerate the agency queue')
  assert.equal((await read(partner)).items.every(item=>item.transaction_id===foreign),true)
  const ownerDriftGeneration=(await q('select dispatch_generation from transaction_handoffs where id=$1',[h.id])).rows[0].dispatch_generation
  assert.equal((await q("select bridge_recover_transaction_handoff($1,$2,'retry','Review the corrupted owner',gen_random_uuid()) result",[h.id,ownerDriftGeneration])).rows[0].result.code,'organisation_authority_required')
  await q("select set_config('test.uid',$1,false)",[user])
  const recoverable=await create()
  await q(`insert into transaction_role_players(id,transaction_id,role_type,assigned_organisation_id,status,assignment_status) values(gen_random_uuid(),$1,'bond_originator',$2,'active','active')`,[recoverable,partner])
  const valid=(await q("select id,dispatch_generation from transaction_handoffs where transaction_id=$1 and role_type='bond_originator'",[recoverable])).rows[0]
  await q("update transaction_handoff_dispatch_jobs set status='retry',reason='delivery_failed' where handoff_id=$1 and generation=$2 and channel='workspace'",[valid.id,valid.dispatch_generation])
  await q('select handoff_private.refresh_dispatch($1)',[valid.id])
  assert.equal((await q("select bridge_recover_transaction_handoff($1,$2,'retry','Reviewed the correct owner',gen_random_uuid()) result",[valid.id,valid.dispatch_generation])).rows[0].result.success,true,'correctly owned recovery remains available')
  await q('set role authenticated')
  assert.equal((await read()).success,true)
  await q('reset role')
  await q('set role anon');await assert.rejects(read(),/permission denied/);await q('reset role')
  console.log('Organisation handoff queue: scope denial, missing register/jobs/native matters/receipts/payloads, expiry, stable age, pagination, completed/closed exclusion and read-only checks passed')
}
