begin;

create table if not exists public.buyer_viewing_preference_links (
  id uuid primary key default gen_random_uuid(),
  organisation_id uuid not null references public.organisations(id) on delete cascade,
  lead_id uuid references public.leads(lead_id) on delete set null,
  contact_email text,
  organisation_name text,
  buyer_name text,
  agent_name text,
  agent_email text,
  token_hash text not null unique,
  status text not null default 'pending',
  selected_property_ids text[] not null default '{}'::text[],
  properties jsonb not null default '[]'::jsonb,
  response jsonb not null default '{}'::jsonb,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_sent_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '14 days'),
  submitted_at timestamptz,
  constraint buyer_viewing_preference_links_status_check
    check (status in ('pending', 'submitted', 'expired', 'revoked'))
);

create index if not exists buyer_viewing_preference_links_org_lead_idx
  on public.buyer_viewing_preference_links (organisation_id, lead_id, created_at desc);

create index if not exists buyer_viewing_preference_links_pending_idx
  on public.buyer_viewing_preference_links (expires_at)
  where status = 'pending';

alter table public.buyer_viewing_preference_links enable row level security;

drop policy if exists buyer_viewing_preference_links_member_select on public.buyer_viewing_preference_links;
create policy buyer_viewing_preference_links_member_select
on public.buyer_viewing_preference_links
for select
to authenticated
using (public.bridge_is_active_member(organisation_id));

drop policy if exists buyer_viewing_preference_links_member_insert on public.buyer_viewing_preference_links;
create policy buyer_viewing_preference_links_member_insert
on public.buyer_viewing_preference_links
for insert
to authenticated
with check (public.bridge_is_active_member(organisation_id));

drop policy if exists buyer_viewing_preference_links_member_update on public.buyer_viewing_preference_links;
create policy buyer_viewing_preference_links_member_update
on public.buyer_viewing_preference_links
for update
to authenticated
using (public.bridge_is_active_member(organisation_id))
with check (public.bridge_is_active_member(organisation_id));

grant select, insert, update on public.buyer_viewing_preference_links to authenticated;

comment on table public.buyer_viewing_preference_links is
  'Tokenised buyer-facing viewing preference sessions generated by the agency viewing planner.';

commit;
